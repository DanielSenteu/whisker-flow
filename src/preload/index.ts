import { contextBridge, ipcRenderer } from 'electron'
import type { Intent, PetProfile, Progress } from '../shared/types'

const api = {
  getProfile: (): Promise<PetProfile | null> => ipcRenderer.invoke('profile:get'),
  saveProfile: (p: PetProfile): Promise<boolean> => ipcRenderer.invoke('profile:save', p),
  finishOnboarding: (): Promise<void> => ipcRenderer.invoke('onboarding:finish'),
  resetProfile: (): Promise<void> => ipcRenderer.invoke('profile:reset'),
  keysStatus: (): Promise<{ gemini: boolean; elevenlabs: boolean }> => ipcRenderer.invoke('keys:status'),
  interpret: (audio: string, mime: string): Promise<Intent> => ipcRenderer.invoke('voice:interpret', { audio, mime }),
  speak: (text: string): Promise<{ ok: true; audio: string } | { ok: false; error: string }> =>
    ipcRenderer.invoke('voice:speak', text),

  // the pet's body: stills + clips generated by Gemini and cached on disk
  createBase: (photo: string, species: string): Promise<{ ok: true; stand: string } | { ok: false; error: string }> =>
    ipcRenderer.invoke('pet:createBase', { photo, species }),
  assets: (): Promise<string[]> => ipcRenderer.invoke('pet:assets'),
  file: (kind: 'still' | 'clip', name: string): Promise<Uint8Array | null> =>
    ipcRenderer.invoke('pet:file', { kind, name }),
  onAssetReady: (cb: (asset: string) => void): void => {
    ipcRenderer.on('pet:asset-ready', (_e, a: string) => cb(a))
  },
  onProgress: (cb: (p: Progress) => void): void => {
    ipcRenderer.on('pet:progress', (_e, p: Progress) => cb(p))
  },
  cursorX: (): Promise<number | null> => ipcRenderer.invoke('screen:cursorX'),
  setClickThrough: (ignore: boolean): void => ipcRenderer.send('pet:clickThrough', ignore)
}

contextBridge.exposeInMainWorld('wf', api)

export type WfApi = typeof api
